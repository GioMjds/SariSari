const getTodayISO = (hour = 8, min = 0): string => {
  const d = new Date();
  d.setHours(hour, min, 0, 0);
  return d.toISOString();
};

const getDaysAgoISO = (daysAgo: number, hour = 8, min = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, min, 0, 0);
  return d.toISOString();
};

